#!/usr/bin/env python3
"""Preview registration grants; --apply explicitly connects as an administrator.

Only supports the dedicated local accounts created by setup_local.py.
Passwords never appear in SQL output or process arguments.
"""
import argparse
import getpass
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[3]
TEMPLATE = Path(__file__).parent / 'migrations/002_registration_grants.sql.template'
TARGETS = {
    'runtime': ('runtime.json', 'asynlog_storage', 'storage_app_'),
    'http-test': ('http-test.json', 'asynlog_storage_test', 'storage_http_'),
}


def load_target(directory, target):
    filename, expected_database, prefix = TARGETS[target]
    path = directory / filename
    try:
        config = json.loads(path.read_text(encoding='utf-8'))
    except (OSError, ValueError):
        raise ValueError(f'{filename}: configuration missing or invalid; no grants executed') from None
    if not isinstance(config, dict):
        raise ValueError(f'{filename}: expected a configuration object')
    user = config.get('STORAGE_DB_USER', '')
    if not isinstance(user, str) or not re.fullmatch(re.escape(prefix) + r'[0-9a-f]{8}', user):
        raise ValueError(f'{filename}: expected the dedicated account generated by setup_local.py')
    if config.get('STORAGE_DB_NAME') != expected_database or config.get('STORAGE_DB_HOST') != '127.0.0.1':
        raise ValueError(f'{filename}: unexpected database or host; use a reviewed manual migration')
    port = str(config.get('STORAGE_DB_PORT', '3306'))
    if not port.isascii() or not port.isdecimal() or not 1 <= int(port) <= 65535:
        raise ValueError(f'{filename}: invalid port')
    return expected_database, user, str(int(port))


def build_plan(directory, targets):
    # Validate ALL selected accounts before connecting or changing privileges.
    records = [load_target(directory, target) for target in targets]
    ports = {port for _, _, port in records}
    if len(ports) != 1:
        raise ValueError('Selected configurations use different servers; migrate each target separately')
    template = TEMPLATE.read_text(encoding='utf-8')
    sql = '\n'.join(template.replace('{{DATABASE}}', database).replace('{{USER}}', user)
                    for database, user, _ in records)
    return sql, ports.pop()


def option(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r') + '"'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config-dir', type=Path, default=ROOT / 'build/local-auth')
    parser.add_argument('--target', choices=('all', *TARGETS), default='all')
    parser.add_argument('--apply', action='store_true', help='execute grants; default only previews SQL')
    parser.add_argument('--admin', default='root', help='administrator used only by this migration')
    parser.add_argument('--mysql', default='mysql', help='MySQL client executable')
    args = parser.parse_args()
    try:
        targets = list(TARGETS) if args.target == 'all' else [args.target]
        sql, port = build_plan(args.config_dir, targets)
        print(sql, flush=True)
        if not args.apply:
            print('PREVIEW ONLY: no database connection and no privileges changed.')
            return 0
        if os.name != 'posix':
            raise ValueError('Run --apply on the Linux deployment host; preview works on Windows')
        if not args.admin or any(c in args.admin for c in '\0\r\n'):
            raise ValueError('Invalid administrator name')
        password = getpass.getpass('MySQL administrator password (not saved): ')
        if '\0' in password:
            raise ValueError('Invalid administrator password input')
        # Private temporary directory and mode 0600 option file, removed on exit.
        with tempfile.TemporaryDirectory(prefix='registration-grant-') as directory:
            defaults = Path(directory) / 'mysql.cnf'
            fd = os.open(defaults, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, 'w', encoding='utf-8') as stream:
                stream.write('[client]\nhost=127.0.0.1\nprotocol=TCP\nport=' + port +
                             '\nuser=' + option(args.admin) + '\npassword=' + option(password) + '\n')
            result = subprocess.run(
                [args.mysql, '--defaults-extra-file=' + str(defaults), '--batch'],
                input=sql, text=True, check=False)
        if result.returncode:
            print('Migration failed. Earlier GRANTs may already have succeeded; inspect and rerun after fixing the cause.')
            return 1
        print('Grants executed. Review SHOW GRANTS above, reconnect the service, then run registration acceptance tests.')
        return 0
    except (ValueError, OSError, EOFError):
        # Do not echo raw configuration or exception payloads that may contain credentials.
        print('Migration not completed: check selected local account configuration, MySQL client, and administrator input.')
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
